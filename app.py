# ДЕРЕКТЕР БАЗАСЫ (SQLite) БАПТАУЛАРЫ
# ---------------------------------------------------------
DB_NAME = "students_results.db"

def init_db():
    conn = sqlite3.connect(DB_NAME, check_same_thread=False)
    cursor = conn.cursor()
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS results (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            student_name TEXT,
            grade TEXT,
            topic TEXT,
            score INTEGER,
            max_score INTEGER,
            percentage REAL,
            timestamp TEXT
        )
    """)
    conn.commit()
    conn.close()

def save_result(student_name, grade, topic, score, max_score, percentage):
    conn = sqlite3.connect(DB_NAME, check_same_thread=False)
    cursor = conn.cursor()
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    cursor.execute("""
        INSERT INTO results (student_name, grade, topic, score, max_score, percentage, timestamp)
        VALUES (?, ?, ?, ?, ?, ?, ?)
    """, (student_name, grade, topic, score, max_score, percentage, now_str))
    conn.commit()
    conn.close()

def get_all_results():
    conn = sqlite3.connect(DB_NAME, check_same_thread=False)
    df = pd.read_sql_query("SELECT id, student_name, grade, topic, score, max_score, percentage, timestamp FROM results ORDER BY id DESC", conn)
    conn.close()
    return df

def clear_all_results():
    conn = sqlite3.connect(DB_NAME, check_same_thread=False)
    cursor = conn.cursor()
    cursor.execute("DELETE FROM results")
    conn.commit()
    conn.close()

init_db()

