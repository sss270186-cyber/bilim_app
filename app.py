def normalize_answer(val):
    if val is None:
        return ""
    val_str = str(val).strip().lower()
    return val_str.replace(" ", "").replace(",", ".")

def check_answer_match(user_val, correct_val):
    u = normalize_answer(user_val)
    c = normalize_answer(correct_val)
    if u == c:
        return True
    try:
        return float(u) == float(c)
    except ValueError:
        return False

